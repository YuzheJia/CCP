// Regenerates app/Hanzi.hs: every Chinese character the game draws, as a pixel
// bitmap. The game's own font only has Latin letters, and Gloss cannot draw system
// fonts, so the characters are rasterised once here and drawn as runs of squares.
//
// macOS only (it uses the system's PingFang SC). After adding a character to a
// string anywhere in app/, add it to `wanted` below and run, from the repo root:
//
//   swift tools/hanzi.swift > app/Hanzi.hs
import CoreGraphics
import CoreText
import Foundation

let wanted = "光属于人民举报违规黑暗灯塔万岁反对超额发荣的过去现在招租五分钟计划电池指示操作借来完成再教育"
let grid = 32

let font = CTFontCreateWithName("PingFangSC-Regular" as CFString, CGFloat(grid) * 0.92, nil)

func bitmap(_ ch: Character) -> [String] {
  let space = CGColorSpaceCreateDeviceGray()
  let ctx = CGContext(data: nil, width: grid, height: grid, bitsPerComponent: 8, bytesPerRow: grid,
                      space: space, bitmapInfo: CGImageAlphaInfo.none.rawValue)!
  ctx.setFillColor(gray: 0, alpha: 1)
  ctx.fill(CGRect(x: 0, y: 0, width: grid, height: grid))
  let attrs: [NSAttributedString.Key: Any] = [
    NSAttributedString.Key(kCTFontAttributeName as String): font,
    NSAttributedString.Key(kCTForegroundColorAttributeName as String): CGColor(gray: 1, alpha: 1)]
  let line = CTLineCreateWithAttributedString(NSAttributedString(string: String(ch), attributes: attrs))
  let ink = CTLineGetImageBounds(line, ctx)
  // Centre the ink in the square.
  let x = (CGFloat(grid) - ink.width) / 2 - ink.minX
  let y = (CGFloat(grid) - ink.height) / 2 - ink.minY
  ctx.textPosition = CGPoint(x: x, y: y)
  CTLineDraw(line, ctx)
  let data = ctx.data!.bindMemory(to: UInt8.self, capacity: grid * grid)
  // Row 0 of the buffer is the top of the image.
  return (0..<grid).map { row in
    String((0..<grid).map { col in data[row * grid + col] > 150 ? "#" : "." })
  }
}

var seen = Set<Character>()
var out = """
-- | Generated by tools/hanzi.swift: do not edit by hand.
--
-- Chinese characters as \(grid) x \(grid) bitmaps, top row first, '#' for ink.
module Hanzi (hanziGrid, hanziBitmap) where

hanziGrid :: Int
hanziGrid = \(grid)

hanziBitmap :: Char -> Maybe [String]
hanziBitmap c = lookup c table

table :: [(Char, [String])]
table =

"""
var first = true
for ch in wanted where !seen.contains(ch) {
  seen.insert(ch)
  let rows = bitmap(ch).map { "\"\($0)\"" }.joined(separator: "\n      , ")
  out += "  \(first ? "[" : ",") ('\(ch)',\n      [ \(rows)\n      ])\n"
  first = false
}
out += "  ]\n"
print(out, terminator: "")
